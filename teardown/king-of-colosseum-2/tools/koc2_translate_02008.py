def main():
    work = os.path.join(WORK, 'work')
    with open(os.path.join(work, 'moves-02008.json'), encoding='utf-8') as f:
        data = json.load(f)
    strings = data['strings']  # list, physical index = position
    translations = {}
    failed = []
    for idx, ja in enumerate(strings):
        idx_str = str(idx)
        if not ja or ja == '－':
            continue
        en = translate_move(ja)
        if en is None:
            failed.append((idx, ja))
        else:
            translations[idx_str] = en
    with open(os.path.join(work, 'translations-02008.json'), 'w', encoding='utf-8') as f:
        json.dump(translations, f, ensure_ascii=False, indent=1, sort_keys=True)
    print(f'translated {len(translations)}/{len(strings)} strings, '
          f'{len(failed)} failed')
    if failed:
        with open(os.path.join(work, 'translation-failures-02008.txt'), 'w', encoding='utf-8') as f:
            for idx, ja in failed:
                f.write(f'{idx}\t{ja}\n')
        print('failures written to work/translation-failures-02008.txt')
        for idx, ja in failed[:40]:
            print(f'  {idx}: {ja}')
    # spot-check dump
    with open(os.path.join(work, 'translation-review-02008.txt'), 'w', encoding='utf-8') as f:
        for idx, ja in enumerate(strings):
            idx_str = str(idx)
            en = translations.get(idx_str, '<FAILED>')
            f.write(f'{idx_str}\t{ja}\t{en}\n')


if __name__ == '__main__':
    main()
