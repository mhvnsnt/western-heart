# ---------- segmenter ----------

FULLWIDTH_DIGITS = str.maketrans('０１２３４５６７８９', '0123456789')
ROMAN = {'Ⅰ': 'I', 'Ⅱ': 'II', 'Ⅲ': 'III', 'Ⅳ': 'IV', 'Ⅴ': 'V',
         'Ⅵ': 'VI', 'Ⅶ': 'VII', 'Ⅷ': 'VIII', 'Ⅸ': 'IX', 'Ⅹ': 'X'}
GREEK = {'α': 'Alpha', 'β': 'Beta', 'γ': 'Gamma', 'δ': 'Delta',
         'Ω': 'Omega', 'ω': 'Omega', 'θ': 'Theta', 'λ': 'Lambda',
         'Σ': 'Sigma', 'σ': 'Sigma', 'μ': 'Mu'}

# Longest-match keys sorted once
_TERM_KEYS = sorted(TERM, key=len, reverse=True)
_WHOLE_KEYS = sorted(WHOLE, key=len, reverse=True)


def _norm_ws(s):
    return re.sub(r'\s+', ' ', s).strip()


def _handle_parens(s, depth=0):
    """Translate parenthetical chunks: （右手） -> (Right Hand)."""
    if depth > 2:
        return s
    m = re.search(r'（([^）]*)）', s)
    if not m:
        return s
    inner = m.group(1)
    inner_en = translate_fragment(inner, depth + 1)
    if inner_en is None:
        return None
    repl = f'({inner_en})'
    s2 = s[:m.start()] + repl + s[m.end():]
    return _handle_parens(s2, depth + 1)


def _handle_suffixes(s):
    """Handle trailing Ｖｅｒ / Ver / ｖｅｒ / 改 / type suffixes."""
    for pat, fmt in [
        (r'([０１２３４５６７８９]+)[Ｖｖ][ｅｅ][ｒｒ]$', r'(\1 Ver)'),
        (r'([０-９]+)Ｖｅｒ$', r'(\1 Ver)'),
        (r'改$', ' (Modified)'),
    ]:
        m = re.search(pat, s)
        if m:
            base = s[:m.start()]
            suffix = fmt
            if '\\1' in fmt:
                suffix = m.group(1).translate(FULLWIDTH_DIGITS)
                suffix = f'({suffix} Ver)'
            base_en = translate_fragment(base)
            if base_en is None:
                return None
            return _norm_ws(base_en + ' ' + suffix)
    return None


def translate_fragment(s, depth=0):
    """Translate one Japanese fragment (no → / ～ splitting)."""
    if not s:
        return ''
    if s in WHOLE:
        return WHOLE[s]
    # parens
    if '（' in s:
        r = _handle_parens(s, depth)
        if r is not None and '（' not in r:
            # r now contains English + possibly untranslated JP chunks; re-segment
            return translate_fragment(r, depth + 1) if any('\u3000' <= c <= '\u9fff' or '\uff00' <= c <= '\uffef' for c in r) else _norm_ws(r)
        if r is None:
            return None
    # full-width year suffix like ’８５ / ‘８４
    m = re.search(r'[’‘]([０-９]{2})$', s)
    if m:
        base = s[:m.start()]
        base_en = translate_fragment(base, depth + 1)
        if base_en is None:
            return None
        return _norm_ws(base_en + " '" + m.group(1).translate(FULLWIDTH_DIGITS))
    # suffixes
    r = _handle_suffixes(s)
    if r is not None:
        return r
    # middle dot separator -> segment each part
    if '・' in s:
        parts = s.split('・')
        out = []
        for p in parts:
            t = translate_fragment(p, depth + 1)
            if t is None:
                return None
            out.append(t)
        return _norm_ws(' '.join(out))
    # greedy longest-match segmentation
    i = 0
    toks = []
    while i < len(s):
        c = s[i]
        # ASCII / half-width passthrough: group letter/digit runs into
        # whole words. English inserted by paren handling (and by the
        # full-width fallback) re-enters this loop — single-char
        # passthrough used to split it into spaced letters
        # ("Powerbomb ( N o r t o n A p p e a l )"). No source string
        # contains half-width alphanumerics, so grouping is safe.
        if ord(c) < 128:
            if c.isalnum():
                m = re.match(r"[A-Za-z0-9]+(?:['.][A-Za-z0-9]+)*", s[i:])
                toks.append(m.group(0))
                i += len(m.group(0))
            else:
                toks.append(c)
                i += 1
            continue
        if c in ROMAN:
            toks.append(ROMAN[c])
            i += 1
            continue
        if c in GREEK:
            toks.append(GREEK[c])
            i += 1
            continue
        if c in '０１２３４５６７８９':
            toks.append(c.translate(FULLWIDTH_DIGITS))
            i += 1
            continue
        if c == '－':
            toks.append('-')
            i += 1
            continue
        if c == '。':
            i += 1
            continue
        # longest TERM / WHOLE match
        matched = None
        for k in _TERM_KEYS:
            if s.startswith(k, i):
                matched = k
                break
        if matched is None:
            for k in _WHOLE_KEYS:
                if s.startswith(k, i):
                    matched = k
                    break
        if matched is None:
            return None
        toks.append(TERM.get(matched) or WHOLE.get(matched))
        i += len(matched)
    return _norm_ws(' '.join(toks))


def translate_move(ja):
    """Full move-name translation: WHOLE -> →/～ split -> fragment."""
    if ja in WHOLE:
        return WHOLE[ja]
    if '→' in ja:
        parts = ja.split('→')
        out = []
        for p in parts:
            t = translate_fragment(p)
            if t is None:
                return None
            out.append(t)
        return _norm_ws(' into '.join(out))
    if '～' in ja:
        parts = ja.split('～')
        out = []
        for p in parts:
            t = translate_fragment(p)
            if t is None:
                return None
            out.append(t)
        return _norm_ws(' to '.join(out))
    return translate_fragment(ja)


