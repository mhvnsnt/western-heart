/* ============================================================
   WESTERN HEART — runtime material resolve (every loaded model)
   Same rules as game/js/material-resolve.js (the CI gate + asset
   pipeline), applied to the three.js scene after GLTFLoader:
     1. resolve: textureless same-model re-exports take their maps from
        the donor model listed in material-status.js (generated by the gate)
     2. repair:  colour maps sRGB, data maps linear; maps whose image never
        decoded are detected
     3. verdict: any mesh still on a missing / placeholder / exporter-default
        material marks the model broken -> it is never offered at select and
        never instanced into a fight (isModelUsable / assertModelUsable).
   ============================================================ */
import * as THREE from 'three';
import { MATERIAL_STATUS } from './material-status.js';
import { PLACEHOLDER_RE, authoredFlat } from './material-resolve.js';

const broken = new Set(Object.keys(MATERIAL_STATUS.quarantine || {}));
const reasons = { ...(MATERIAL_STATUS.quarantine || {}) };

export function isModelUsable(key) { return !broken.has(key); }
export function materialReason(key) { return reasons[key] || null; }
export function donorFor(key) { return (MATERIAL_STATUS.resolve || {})[key] || null; }
export function assertModelUsable(key) {
  if (broken.has(key)) throw new Error(`model ${key} blocked by material gate: ${reasons[key]}`);
}

const MAPS_SRGB = ['map', 'emissiveMap'];
const MAPS_LINEAR = ['normalMap', 'roughnessMap', 'metalnessMap', 'aoMap'];

/** Material objects of a parsed glTF, by glTF material index. */
async function materialsByIndex(gltf) {
  const n = (gltf.parser.json.materials || []).length;
  return Promise.all([...Array(n).keys()].map(i => gltf.parser.getDependency('material', i)));
}

function verdict(o, m) {
  if (!m) return 'missing';
  if (m.map) return m.map.image ? 'ok' : 'missing';
  if (o.geometry && o.geometry.attributes.color && m.vertexColors) return 'ok';
  if (PLACEHOLDER_RE.test((m.name || '').trim())) return 'placeholder';
  const c = m.color;
  if (c && authoredFlat([c.r, c.g, c.b])) return 'ok';
  return 'untextured';
}

/** Run on every model at ingest. getDonorGltf(key) -> Promise<gltf>. */
export async function resolveModelMaterials(key, gltf, getDonorGltf) {
  const plan = donorFor(key);
  if (plan && getDonorGltf) {
    const dg = await getDonorGltf(plan.donor);
    const [tm, dm] = await Promise.all([materialsByIndex(gltf), materialsByIndex(dg)]);
    const swap = new Map();
    for (const [ti, di] of Object.entries(plan.map)) {
      const src = dm[+di], dst = tm[+ti];
      if (!src || !dst) continue;
      const m = src.clone(); m.name = dst.name; swap.set(dst, m);
    }
    gltf.scene.traverse(o => {
      if (!o.isMesh) return;
      if (Array.isArray(o.material)) o.material = o.material.map(x => swap.get(x) || x);
      else if (swap.has(o.material)) o.material = swap.get(o.material);
    });
  }
  const counts = { ok: 0, missing: 0, placeholder: 0, untextured: 0 };
  gltf.scene.traverse(o => {
    if (!o.isMesh) return;
    for (const m of [].concat(o.material)) {
      if (m) {
        for (const k of MAPS_SRGB) if (m[k]) m[k].colorSpace = THREE.SRGBColorSpace;
        for (const k of MAPS_LINEAR) if (m[k]) m[k].colorSpace = THREE.NoColorSpace;
      }
      counts[verdict(o, m)]++;
    }
  });
  const bad = counts.missing + counts.placeholder + counts.untextured;
  if (bad) {
    broken.add(key);
    reasons[key] = reasons[key] || Object.entries(counts).filter(([k, n]) => k !== 'ok' && n).map(([k, n]) => `${n} ${k}`).join(', ');
    console.error(`[WH] material gate: ${key} blocked (${reasons[key]})`);
  }
  return { key, counts, resolvedFrom: plan ? plan.donor : null, usable: !bad };
}
