/* ============================================================
   WESTERN HEART — runtime material resolve (every loaded model)
   Same rules as game/js/material-resolve.js (the CI gate + asset
   pipeline), applied to the three.js scene after GLTFLoader:
     1. resolve: textureless same-model re-exports take their maps from
        the donor model listed in material-status.js (generated by the gate)
     2. repair:  colour maps sRGB, data maps linear; maps whose image never
        decoded are detected
     3. verdict: any mesh still on a missing / placeholder / exporter-default
        material marks the model broken -> it is never offered at select and
        never instanced into a fight (isModelUsable / assertModelUsable).
   ============================================================ */
import * as THREE from 'three';
import { MATERIAL_STATUS } from './material-status.js';
import { PLACEHOLDER_RE, authoredFlat } from './material-resolve.js';

const broken = new Set(Object.keys(MATERIAL_STATUS.quarantine || {}));
const reasons = { ...(MATERIAL_STATUS.quarantine || {}) };

// RUNTIME-TINTED TEMPLATE EXEMPTION (owner decision 2026-11-02, option A:
// "Narrow the gate rule for runtime-tinted template bodies" — NOT a rebake).
// Mirrors tools/assets/material_gate.mjs: the 9 Creation Suite template
// bodies (customization/templates/meshes/*.glb) ship MB-Lab materials with
// no baked base-colour texture; their skin colour is applied at runtime by
// createInstance (custom fighter, colorize: true, tintStrength 0.3). An
// "untextured"-only verdict on exactly these keys is therefore usable, not
// broken. Missing or placeholder verdicts are NEVER exempted, and no other
// key is exempted.
const RUNTIME_TINTED_TEMPLATES = new Set([
  'custom-template-super-heavyweight', 'custom-template-powerhouse',
  'custom-template-showman', 'custom-template-technician',
  'custom-template-highflyer', 'custom-template-luchador',
  'custom-template-powerhouse-w', 'custom-template-athletic-w',
  'custom-template-striker-w',
]);

// OWNER OUTFIT-NOT-THE-GATE EXEMPTION (owner rule 2026-11-03: "if a fighter
// has no outfit textures, show her without the outfit — what matters is her
// skin texture, eyes, and hair; outfits can be added later from parts").
// Mirrors tools/assets/material_gate.mjs: Megami's playable variant
// (model-rigged-nooutfit.glb) excludes the textureless 24_/25_ outfit +
// headgear shells, which never had textures in her source file. Her skin,
// eyes and hair are textured from her own source. The remaining untextured
// verdicts are source-faithful traits: clear eye shells (EyeMoisture /
// Cornea, transparent by design), one hair-strand material (Bangs1-1 — no
// strand texture exists in any copy of her source), the inner Torso-6 shell
// (textureless in the source itself), and shoe / panties parts carrying
// authored near-black colours. An untextured-only verdict on exactly these
// keys, with no 24_/25_ outfit material left in the model, is therefore
// usable, not broken. Missing or placeholder verdicts are NEVER exempted,
// and no other key is exempted.
// FIDELITY REBUILD (2026-11-05): Megami's loaded model is now the rebuild
// from her recovered commission blend, WITH the outfit — and in the blend
// the outfit is fully textured (the textureless-shell premise described
// the stripped 2026-10-23 conversion, not her source). The exemption's
// outfit test below therefore voids only on a TEXTURELESS 24_/25_ outfit
// material; her textured outfit no longer trips it. The untextured
// verdicts that remain are the same source-faithful classes named above.
const OWNER_OUTFIT_RULE_EXEMPT = new Set(['megami', 'megami-attire1']);

export function isModelUsable(key) { return !broken.has(key); }
export function materialReason(key) { return reasons[key] || null; }
export function donorFor(key) { return (MATERIAL_STATUS.resolve || {})[key] || null; }
export function assertModelUsable(key) {
  if (broken.has(key)) throw new Error(`model ${key} blocked by material gate: ${reasons[key]}`);
}

const MAPS_SRGB = ['map', 'emissiveMap'];
const MAPS_LINEAR = ['normalMap', 'roughnessMap', 'metalnessMap', 'aoMap'];

/** Material objects of a parsed glTF, by glTF material index. */
async function materialsByIndex(gltf) {
  const n = (gltf.parser.json.materials || []).length;
  return Promise.all([...Array(n).keys()].map(i => gltf.parser.getDependency('material', i)));
}

function verdict(o, m) {
  if (!m) return 'missing';
  if (m.map) return m.map.image ? 'ok' : 'missing';
  if (o.geometry && o.geometry.attributes.color && m.vertexColors) return 'ok';
  if (PLACEHOLDER_RE.test((m.name || '').trim())) return 'placeholder';
  const c = m.color;
  if (c && authoredFlat([c.r, c.g, c.b])) return 'ok';
  return 'untextured';
}

/** Run on every model at ingest. getDonorGltf(key) -> Promise<gltf>. */
export async function resolveModelMaterials(key, gltf, getDonorGltf) {
  const plan = donorFor(key);
  if (plan && getDonorGltf) {
    const dg = await getDonorGltf(plan.donor);
    const [tm, dm] = await Promise.all([materialsByIndex(gltf), materialsByIndex(dg)]);
    const swap = new Map();
    for (const [ti, di] of Object.entries(plan.map)) {
      const src = dm[+di], dst = tm[+ti];
      if (!src || !dst) continue;
      const m = src.clone(); m.name = dst.name; swap.set(dst, m);
    }
    gltf.scene.traverse(o => {
      if (!o.isMesh) return;
      if (Array.isArray(o.material)) o.material = o.material.map(x => swap.get(x) || x);
      else if (swap.has(o.material)) o.material = swap.get(o.material);
    });
  }
  const counts = { ok: 0, missing: 0, placeholder: 0, untextured: 0 };
  let outfitShellPresent = false;
  gltf.scene.traverse(o => {
    if (!o.isMesh) return;
    for (const m of [].concat(o.material)) {
      if (m) {
        for (const k of MAPS_SRGB) if (m[k]) m[k].colorSpace = THREE.SRGBColorSpace;
        for (const k of MAPS_LINEAR) if (m[k]) m[k].colorSpace = THREE.NoColorSpace;
      }
      const v = verdict(o, m);
      // A 24_/25_ outfit material only voids the owner exemption when it is
      // itself textureless (the 2026-11-03 shells). Since the 2026-11-05
      // fidelity rebuild, Megami's 24_/25_ outfit materials carry her source
      // textures — a textured outfit is the real outfit, not a shell.
      if (m && /^2[45]_/.test((m.name || '').trim()) && v !== 'ok') outfitShellPresent = true;
      counts[v]++;
    }
  });
  const bad = counts.missing + counts.placeholder + counts.untextured;
  const runtimeTinted = RUNTIME_TINTED_TEMPLATES.has(key) &&
    counts.missing === 0 && counts.placeholder === 0 && counts.untextured > 0;
  const ownerOutfitRule = OWNER_OUTFIT_RULE_EXEMPT.has(key) && !outfitShellPresent &&
    counts.missing === 0 && counts.placeholder === 0 && counts.untextured > 0;
  if (bad && !runtimeTinted && !ownerOutfitRule) {
    broken.add(key);
    reasons[key] = reasons[key] || Object.entries(counts).filter(([k, n]) => k !== 'ok' && n).map(([k, n]) => `${n} ${k}`).join(', ');
    console.error(`[WH] material gate: ${key} blocked (${reasons[key]})`);
  }
  return { key, counts, resolvedFrom: plan ? plan.donor : null, usable: !bad || runtimeTinted || ownerOutfitRule, runtimeTinted, ownerOutfitRule };
}
