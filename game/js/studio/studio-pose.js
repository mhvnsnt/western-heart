/* STANCE EDITOR — port of Bannon's poseStudio (index.html L18846) on the
   CREATION SUITE template. Slots: selectPose (select screen), fightPose
   (fight stance overlay), winPose, entrancePose (stored; consumers land with
   the Win/Entrance editors), plus ANIMATE (keyframes → clips.custom).
   Pieces: T7 Customization L1/R1 tabs, Fire Pro Edit silhouette part picker,
   Wrestling Empire tap-the-body select, 2K19 one-tap presets + legend footer. */
import { JOINTS, LABELS, MIRROR, LOCKED_SELECT_POSE, loadDB, saveDB, fighter, patchFighter, mirrorRot } from './studio-store.js';
import { boneIndex, findBone, applyPoseOverlay, normBone } from './studio-apply.js';

const DEG = Math.PI / 180;
export const SLOTS = [['selectPose', 'SELECT'], ['fightPose', 'FIGHT'], ['winPose', 'WIN'], ['entrancePose', 'ENTRANCE'], ['anim', 'ANIMATE']];
const d = (x, y, z) => [x * DEG, y * DEG, z * DEG];
/* one-tap presets: right side authored, left side generated by mirrorRot */
const RAW = {
  'NEUTRAL': {},
  'GUARD UP': { RightArm: d(-50, 0, 60), RightForeArm: d(0, 0, 110), Spine1: d(8, 0, 0) },
  'FISTS LOW': { RightArm: d(-20, 0, 20), RightForeArm: d(0, 0, 70) },
  'ARMS CROSSED': { RightArm: d(-35, -40, 30), RightForeArm: d(0, -20, 120) },
  'FLEX': { RightArm: d(0, 0, 80), RightForeArm: d(0, 0, 120), Spine1: d(-6, 0, 0) },
  'ARMS OUT': { RightArm: d(0, 0, -10), Head: d(-10, 0, 0) },
  'HANDS ON HIPS': { RightArm: d(10, 20, 45), RightForeArm: d(0, 30, 90) },
  'LEAN IN': { Spine: d(14, 0, 0), Spine1: d(10, 0, 0), Head: d(-12, 0, 0) },
};
export function presetPose(name){ const p = JSON.parse(JSON.stringify(RAW[name] || {})); for (const j of Object.keys(p)) if (MIRROR[j] && !p[MIRROR[j]]) p[MIRROR[j]] = mirrorRot(p[j]); return p; }
export const PRESETS = Object.keys(RAW);

export function samplePoseKeys(keys, t){
  if (!keys.length) return {}; if (keys.length === 1 || t <= keys[0].t) return keys[0].pose;
  for (let i = 1; i < keys.length; i++) { const a = keys[i - 1], b = keys[i]; if (t <= b.t) { const u = (t - a.t) / Math.max(1e-6, b.t - a.t); const out = {};
    for (const j of new Set([...Object.keys(a.pose), ...Object.keys(b.pose)])) { const p = a.pose[j] || [0,0,0], q = b.pose[j] || [0,0,0]; out[j] = [0,1,2].map(k => p[k] + (q[k] - p[k]) * u); } return out; } }
  return keys[keys.length - 1].pose;
}
/* silhouette joint coords (64x150 viewbox), front view: model's right = viewer's left */
const SIL = { Head:[32,12], Neck:[32,24], Spine1:[32,38], Spine:[32,54], Hips:[32,68],
  RightShoulder:[22,28], RightArm:[16,36], RightForeArm:[11,54], RightHand:[8,70],
  LeftShoulder:[42,28], LeftArm:[48,36], LeftForeArm:[53,54], LeftHand:[56,70],
  RightUpLeg:[25,80], RightLeg:[23,106], RightFoot:[22,138], LeftUpLeg:[39,80], LeftLeg:[41,106], LeftFoot:[42,138] };

export function mountPoseStudio(ctx){
  const { viewer, el, toast, getFighterId, setTabs, setFooter, sil, onPickBone, back } = ctx;
  const S = { slot: 'selectPose', edit: 'selectPose', sel: 'RightArm', mirror: true, work: {}, keys: [], dur: 1.5, playT: 0, playing: false, rest: null, idx: null };
  function captureRest(){ S.idx = boneIndex(viewer.model); S.rest = new Map(); for (const k in S.idx) S.rest.set(S.idx[k], S.idx[k].quaternion.clone()); }
  function loadSlot(){ const f = loadDB().fighters[getFighterId()] || {}; S.work = JSON.parse(JSON.stringify(f[S.edit] || {})); const c = (f.clips || {}).custom; S.keys = c ? c.keys : []; S.dur = c ? c.dur : 1.5; }
  viewer.onFrame = (dt) => {
    if (!viewer.model) return; if (!S.rest || S.restModel !== viewer.model) { captureRest(); S.restModel = viewer.model; }
    for (const [b, q] of S.rest) b.quaternion.copy(q);
    let pose = S.work;
    if (S.playing && S.keys.length) { S.playT = (S.playT + dt) % S.dur; pose = samplePoseKeys(S.keys, S.playT); const tl = el.querySelector('#ps-tl'); if (tl) tl.value = S.playT; }
    applyPoseOverlay(viewer.model, pose, 1, { idx: S.idx, model: viewer.model });
  };
  const cur = () => (S.work[S.sel] ||= [0, 0, 0]);
  function syncMirror(){ if (S.mirror && MIRROR[S.sel]) S.work[MIRROR[S.sel]] = mirrorRot(cur()); }
  function setAxis(a, v){ v = Math.max(-180 * DEG, Math.min(180 * DEG, v)); cur()[a] = v; syncMirror(); }
  const locked = () => S.edit === 'selectPose' && LOCKED_SELECT_POSE.has(getFighterId());
  function pick(j){ S.sel = j; render(); }
  onPickBone(b => { const n = normBone(b.name); const j = JOINTS.find(x => normBone(x) === n); if (j) pick(j); });
  function drawSil(){
    sil.innerHTML = `<svg viewBox="0 0 64 150"><path d="M32 12V68M22 28H42M22 28L8 70M42 28L56 70M32 68L22 138M32 68L42 138" stroke="#fff5" stroke-width="2" fill="none"/>${JOINTS.map(j => `<circle data-j="${j}" cx="${SIL[j][0]}" cy="${SIL[j][1]}" r="${j === 'Head' ? 6 : 4}" class="${j === S.sel ? 'sel' : ''}"><title>${LABELS[j]}</title></circle>`).join('')}</svg>`;
    sil.querySelectorAll('[data-j]').forEach(c => c.onclick = () => pick(c.dataset.j));
  }
  function footer(){
    if (S.slot === 'anim') return setFooter([{ k: 'b', label: 'BACK', fn: back }, { k: 'x', label: 'KEY', fn: addKey }, { k: 'y', label: S.playing ? 'STOP' : 'PLAY', fn: () => { S.playing = !S.playing; render(); } }, { k: 'a', label: 'SAVE ANIM', pri: true, fn: saveClip }]);
    setFooter([{ k: 'b', label: 'BACK', fn: back }, { k: 'y', label: 'MIRROR ' + (S.mirror ? 'ON' : 'OFF'), fn: () => { S.mirror = !S.mirror; render(); } },
      { k: 'x', label: 'RESET', fn: () => { S.work[S.sel] = [0,0,0]; syncMirror(); render(); } },
      { k: 'a', label: locked() ? 'LOCKED' : 'SAVE', pri: true, disabled: locked(), fn: save }]);
  }
  function save(){ if (locked()) return; const clean = {}; for (const j in S.work) if (S.work[j].some(v => Math.abs(v) > 1e-4)) clean[j] = S.work[j]; patchFighter(getFighterId(), { [S.edit]: clean }); toast(SLOTS.find(s => s[0] === S.edit)[1] + ' pose saved'); }
  function addKey(){ const t = S.keys.length ? Math.min(S.dur, S.playT || S.keys[S.keys.length - 1].t + 0.25) : 0; S.keys = S.keys.filter(k => Math.abs(k.t - t) > 0.01); S.keys.push({ t, pose: JSON.parse(JSON.stringify(S.work)) }); S.keys.sort((a, b) => a.t - b.t); S.dur = Math.max(S.dur, t); S.playT = t; render(); toast('Keyframe at ' + t.toFixed(2) + 's'); }
  function saveClip(){ const db = loadDB(); const f = fighter(db, getFighterId()); (f.clips ||= {}).custom = { dur: S.dur, keys: S.keys }; saveDB(db); toast('Animation saved'); }
  function render(){
    drawSil(); footer();
    const p = cur(); const missing = viewer.model && S.idx && !findBone(S.idx, S.sel);
    const ji = JOINTS.indexOf(S.sel);
    const part = `<div class="part"><button data-pj="-1" aria-label="Previous part">‹</button><div class="pn">${LABELS[S.sel]}${missing ? ' <span class="note">(no bone on this rig)</span>' : ''}</div><button data-pj="1" aria-label="Next part">›</button></div>`;
    if (S.slot === 'anim') {
      el.innerHTML = `${part}<div class="lbl">TIMELINE · ${S.keys.length} KEYS · ${S.dur.toFixed(2)}s</div>
        <label class="sl" style="grid-template-columns:50px 1fr"><span>TIME</span><input type="range" id="ps-tl" min="0" max="${S.dur}" step="0.01" value="${S.playT}"></label>
        <div class="presets"><button id="ps-lib">SAVE POSE TO LIBRARY</button><button id="ps-clr">CLEAR KEYS</button></div>
        <div class="note">Pose the fighter on any tab, then KEY here. Saved animations feed Animation Studio and Create a Move.</div>`;
      el.querySelector('#ps-tl').oninput = (e) => { S.playing = false; S.playT = +e.target.value; S.work = JSON.parse(JSON.stringify(samplePoseKeys(S.keys, S.playT))); };
      el.querySelector('#ps-lib').onclick = () => { const db = loadDB(); const n = 'pose-' + Object.keys(db.library.poses).length; db.library.poses[n] = { from: getFighterId(), pose: S.work }; saveDB(db); toast('Saved to library as ' + n); };
      el.querySelector('#ps-clr').onclick = () => { S.keys = []; S.playT = 0; render(); };
    } else {
      el.innerHTML = `${part}
        ${['TILT', 'TURN', 'TWIST'].map((n, a) => { const v = Math.round(p[a] / DEG); return `<div class="sl" data-a="${a}"><span>${n}</span><button data-s="-15">«</button><button data-s="-1">‹</button><input type="range" min="-180" max="180" step="1" value="${v}" aria-label="${n}"><button data-s="1">›</button><button data-s="15">»</button><output>${v}°</output></div>`; }).join('')}
        <div class="presets">${PRESETS.map(n => `<button data-p="${n}">${n}</button>`).join('')}</div>
        <div class="note">${locked() ? 'This fighter\'s select pose is locked by the owner.' : S.edit === 'selectPose' ? 'Shows on character select. Tap the model or the body map to pick a part.' : S.edit === 'fightPose' ? 'Rides on top of the real Tekken stance in fights.' : 'Saved for the ' + (S.edit === 'winPose' ? 'win' : 'entrance') + ' scene.'}</div>`;
      el.querySelectorAll('.sl').forEach(row => { const a = +row.dataset.a, r = row.querySelector('input'), o = row.querySelector('output');
        const upd = () => { r.value = Math.round(cur()[a] / DEG); o.textContent = r.value + '°'; };
        r.oninput = () => { setAxis(a, r.value * DEG); upd(); };
        row.querySelectorAll('[data-s]').forEach(b => b.onclick = () => { setAxis(a, cur()[a] + (+b.dataset.s) * DEG); upd(); }); });
      el.querySelectorAll('[data-p]').forEach(b => b.onclick = () => { S.work = presetPose(b.dataset.p); render(); toast(b.dataset.p); });
    }
    el.querySelectorAll('[data-pj]').forEach(b => b.onclick = () => pick(JOINTS[(ji + (+b.dataset.pj) + JOINTS.length) % JOINTS.length]));
  }
  setTabs(SLOTS, S.slot, (k) => { S.slot = k; if (k !== 'anim') { S.edit = k; loadSlot(); } render(); });
  loadSlot(); render();
  return { refresh(){ S.rest = null; loadSlot(); render(); }, state: S };
}
