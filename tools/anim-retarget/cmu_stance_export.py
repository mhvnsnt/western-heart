def parse(p):
    t=open(p).read().split('MOTION')
    toks=t[0].split('\n');joints=[];stack=[];cur=None
    for l in toks:
        w=l.split()
        if not w:continue
        if w[0] in('ROOT','JOINT'):
            j={'name':w[1],'parent':stack[-1] if stack else -1,'off':None,'ch':[]};joints.append(j);cur=len(joints)-1
        elif w[0]=='End':
            joints.append({'name':'_end','parent':cur,'off':None,'ch':[]});cur=len(joints)-1
        elif w[0]=='{':stack.append(cur)
        elif w[0]=='}':stack.pop();cur=stack[-1] if stack else None
        elif w[0]=='OFFSET':joints[cur]['off']=np.array(list(map(float,w[1:4])))
        elif w[0]=='CHANNELS':joints[cur]['ch']=w[2:]
    m=t[1].strip().split('\n');ft=float(m[1].split(':')[1])
    data=np.array([list(map(float,l.split())) for l in m[2:]])
    return joints,data,ft
