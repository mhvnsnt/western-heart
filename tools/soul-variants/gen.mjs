#!/usr/bin/env node
// Generates game/data/soul-variants.json: per-fighter (and per-form) variant sets
// for the four soul systems, from roster + bio/title + forms + real moveset move types.
// Formula documented in docs/design/SOUL-SYSTEMS.md. Names go through tools/canon.
// Usage: node tools/soul-variants/gen.mjs [--map PRIVATE/naming/CANON-NAME-MAP.json]
import fs from 'node:fs';
import { rename, loadMap, leaks } from '../canon/canon.mjs';
const root = new URL('../../', import.meta.url).pathname;
const { FULL_ROSTER } = await import(root + 'game/js/roster-full.js');
const mi = process.argv.indexOf('--map'); const map = loadMap(mi > 0 ? process.argv[mi + 1] : process.env.WH_CANON_MAP);
const deny = JSON.parse(fs.readFileSync(root + 'tools/canon/denylist.json', 'utf8')).terms;
export const SYSTEMS = {
  kesshou: { en: 'KESSHOU', ja: '結章' }, release: { en: 'NINE-SOUL RELEASE', ja: '九魂解放' },
  reihou: { en: 'REIHOU', ja: '霊放' }, seal: { en: "TRIAL'S SEAL", ja: '試練の封' } };
const LORE = /\b(god|devil|demon|king|emperor|boss|master|legend|lord|true|final|ancient|soul|spirit|oni|dragon)\b/i;
const TYPE_LABEL = { strike: 'Strike', throw: 'Throw', grab: 'Grapple', low: 'Low', mid: 'Mid', high: 'High', heavy: 'Heavy',
  hand: 'Fist', foot: 'Kick', launcher: 'Launch', special: 'Special', unblockable: 'Unblockable', power: 'Power', counter: 'Counter', aerial: 'Aerial' };
const SUFFIX = { kesshou: 'Chapter', release: 'Release', reihou: 'Flare', seal: 'Seal' };
function moveTypes(movesetId) {
  const p = root + `game/assets/movesets/${movesetId}.json`; if (!fs.existsSync(p)) return { types: ['strike', 'mid'], moves: 0 };
  const d = JSON.parse(fs.readFileSync(p, 'utf8')); const mv = Array.isArray(d.moves) ? d.moves : Object.values(d.moves || {});
  const t = new Set();
  for (const m of mv) { if (!m || typeof m !== 'object') continue;
    if (m.move_class) t.add(String(m.move_class).toLowerCase().split(/\W/)[0]);
    const hl = String(m.hit_level || (m.t7 && m.t7.hit_level) || '').toLowerCase();
    for (const k of ['low', 'mid', 'high']) if (hl.includes(k)) t.add(k); if (hl.includes('throw')) t.add('throw');
    if (m.heavy) t.add('heavy'); if (/arm|hand/i.test(m.limb || '')) t.add('hand'); if (/leg|foot/i.test(m.limb || '')) t.add('foot');
    if ((m.knock || 0) >= 4 || m.launch || m.launcher) t.add('launcher'); if (m.unblockable) t.add('unblockable'); }
  return { types: [...t].filter(x => TYPE_LABEL[x]), moves: mv.length };
}
export function powerTier(ch, mt) {
  const forms = Array.isArray(ch.forms) ? ch.forms.length : ch.forms ? Object.keys(ch.forms).length : 0;
  return 1 + (LORE.test(`${ch.title || ''} ${ch.name || ''}`) ? 2 : 0) + (ch.archetype === 'Boss' ? 2 : 0)
    + Math.min(2, forms) + (mt.types.length >= 8 ? 1 : 0) + (mt.moves >= 300 ? 1 : 0);
}
export const countFor = tier => Math.max(3, Math.min(8, 3 + Math.floor(tier / 2)));
function setFor(types, n, sys) {
  const pool = types.length ? types : ['strike']; const out = [];
  for (let i = 0; i < n; i++) { const ty = pool[i % pool.length]; const lvl = Math.floor(i / pool.length);
    out.push({ id: `${sys}-${ty}${lvl ? '-' + (lvl + 1) : ''}`, moveType: ty, name: `${SYSTEMS[sys].en} · ${TYPE_LABEL[ty]} ${SUFFIX[sys]}${lvl ? ' ' + 'II III IV V'.split(' ')[lvl - 1] : ''}`,
      ja: SYSTEMS[sys].ja, power: +(1 + 0.05 * i).toFixed(2) }); }
  return out;
}
const fighters = {};
for (const ch of FULL_ROSTER) {
  if (!ch || !ch.id) continue;
  const mt = moveTypes(ch.moveset || ch.id); const tier = powerTier(ch, mt); const n = countFor(tier);
  const sets = Object.fromEntries(Object.keys(SYSTEMS).map(s => [s, setFor(mt.types, n, s)]));
  const forms = {}; const fl = Array.isArray(ch.forms) ? ch.forms : ch.forms ? Object.keys(ch.forms) : [];
  for (const f of fl) { const fid = typeof f === 'string' ? f : (f.id || f.name); if (!fid) continue;
    const fmt = moveTypes(`${ch.id}-${fid}`); const ft = fmt.moves ? fmt.types : mt.types;
    forms[fid] = Object.fromEntries(Object.keys(SYSTEMS).map(s => [s, setFor(ft, Math.max(3, n - 1), s)])); }
  fighters[ch.id] = { tier, min: n, moveTypes: mt.types, ...sets, forms };
}
const out = rename({ _doc: 'GENERATED by tools/soul-variants/gen.mjs — see docs/design/SOUL-SYSTEMS.md', systems: SYSTEMS, fighters }, map);
const txt = JSON.stringify(out, null, 1); const bad = leaks(txt, deny);
if (bad.length) { console.error('canon leak:', bad); process.exit(2); }
fs.writeFileSync(root + 'game/data/soul-variants.json', txt);
const c = Object.values(fighters).map(f => f.min); console.log('soul-variants:', c.length, 'fighters, min', Math.min(...c), 'max', Math.max(...c));
