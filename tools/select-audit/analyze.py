#!/usr/bin/env python3
"""analyze.py <captureDir> <out.md> <sheet.png> [label]
Turns capture.js results.jsonl into a per-fighter status table + contact sheet.
Checks: T-pose/bind pose, deformation outliers, zero/wrong weights, duplicate poses."""
import json, sys, os, math, itertools
from PIL import Image, ImageDraw
cap, md, sheet = sys.argv[1:4]; label = sys.argv[4] if len(sys.argv) > 4 else ''
rows = [json.loads(l) for l in open(os.path.join(cap, 'results.jsonl')) if l.strip()]
J = ['LeftArm', 'LeftForeArm', 'RightArm', 'RightForeArm', 'LeftUpLeg', 'LeftLeg', 'RightUpLeg', 'RightLeg', 'Spine', 'Neck']
def joints(r):
    v = r.get('poseVec') or []; d = {}
    for i in range(0, len(v) - 3, 4):
        n = str(v[i]).split(':')[-1]
        d.setdefault(n, v[i+1:i+4])
    return {k: d[k] for k in J if k in d}
TH = dict(tpose=70, bind=4, edge=0.004, far=0.03, zero=0.001, bbox_hi=1.45, bbox_lo=0.55, dup=0.06)
for r in rows:
    f = []
    if r.get('error'): f.append('LOAD:' + r['error'][:60])
    else:
        a, b = r.get('armL'), r.get('armR')
        if a is not None and b is not None and a > TH['tpose'] and b > TH['tpose']: f.append(f'T-POSE (arms {a:.0f}/{b:.0f} deg from down)')
        if (r.get('maxBoneDevDeg') or 0) < TH['bind']: f.append('BIND-POSE (no bone moved from rest)')
        if (r.get('edgeFrac') or 0) > TH['edge']: f.append(f"STRETCHED-TRIS {r['edgeFrac']*100:.2f}%")
        if (r.get('farFrac') or 0) > TH['far']: f.append(f"WRONG-BONE-WEIGHTS {r['farFrac']*100:.1f}%")
        if (r.get('zeroFrac') or 0) > TH['zero']: f.append(f"ZERO-WEIGHT {r['zeroFrac']*100:.2f}%")
        br = r.get('bboxRatio') or 1
        if br > TH['bbox_hi'] or br < TH['bbox_lo']: f.append(f'BBOX {br}')
        if a is None: f.append('NO-ARM-BONES')
    r['_flags'] = f; r['_j'] = joints(r); r['_dups'] = []
for x, y in itertools.combinations([r for r in rows if not r.get('error')], 2):
    ks = set(x['_j']) & set(y['_j'])
    if len(ks) < 6: continue
    d = sum(math.dist(x['_j'][k], y['_j'][k]) for k in ks) / len(ks)
    same_clip = x.get('stance') == 'cmu-14_01' and y.get('stance') == 'cmu-14_01'
    if d < TH['dup'] or same_clip:
        x['_dups'].append(y['id']); y['_dups'].append(x['id'])
for r in rows:
    if r['_dups']: r['_flags'].append('DUP-POSE with ' + ','.join(sorted(set(r['_dups']))))
bad = [r for r in rows if r['_flags']]
with open(md, 'w') as o:
    o.write(f"# Select-screen audit {label}\n\nGenerated by `tools/select-audit` (capture.js + probe.js + analyze.py) at 390x844, headless Chromium. "
            f"{len(rows)} fighters, {len(rows)-len(bad)} pass, {len(bad)} fail.\n\nThresholds: {json.dumps(TH)}\n\n")
    o.write('| fighter | status | stance source | clip | arms L/R deg | bone dev deg | edge% | far% | zero% | bbox | flags |\n|---|---|---|---|---|---|---|---|---|---|---|\n')
    for r in rows:
        clip = ','.join(r.get('mixerClip') or [])[:40]
        o.write(f"| {r['id']} | {'FAIL' if r['_flags'] else 'PASS'} | {r.get('stance') or '-'} | {clip} | {r.get('armL')}/{r.get('armR')} | {r.get('maxBoneDevDeg')} | "
                f"{(r.get('edgeFrac') or 0)*100:.2f} | {(r.get('farFrac') or 0)*100:.1f} | {(r.get('zeroFrac') or 0)*100:.2f} | {r.get('bboxRatio')} | {'; '.join(r['_flags'])} |\n")
json.dump([{k: v for k, v in r.items() if k not in ('poseVec', '_j')} for r in rows], open(os.path.join(cap, 'status.json'), 'w'), indent=1)
# contact sheet: hero + card per fighter
C, HW, HH = 6, 195, 300
W = Image.new('RGB', (C * HW, ((len(rows) + C - 1) // C) * (HH + 34)), '#111'); d = ImageDraw.Draw(W)
for k, r in enumerate(rows):
    x, y = (k % C) * HW, (k // C) * (HH + 34)
    p = os.path.join(cap, r['id'] + '-hero.png')
    if os.path.exists(p):
        im = Image.open(p).convert('RGB'); im.thumbnail((HW, HH)); W.paste(im, (x, y + 34))
    pc = os.path.join(cap, r['id'] + '-card.png')
    if os.path.exists(pc):
        im = Image.open(pc).convert('RGB'); im.thumbnail((60, 80)); W.paste(im, (x + HW - im.width, y + 34))
    d.text((x + 3, y + 2), r['id'], fill='white')
    d.text((x + 3, y + 16), ('FAIL ' + (r['_flags'][0] if r['_flags'] else ''))[:34] if r['_flags'] else 'PASS', fill='#ff5555' if r['_flags'] else '#55ff77')
W.save(sheet); print(len(rows), 'fighters', len(bad), 'fail')
