#!/usr/bin/env python3
"""Per-fighter moveset coverage vs the source character's full T8 / T7 data.

For every fighter in game/js/roster-full.js: its tekken_base -> T8 (wavu, frame-data-t8-full +
frame-data) and T7 (t7chicken) records via merge_sources.bases_for, then counts how many of those
source records the fighter's game/assets/movesets/<id>.json carries (t8_id / merge_source / t7.id).
    python3 tools/moveset-merge/coverage_table.py > docs/movesets/COVERAGE-2026-10-23.md
"""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import merge_sources as M  # noqa: E402
import notation as N  # noqa: E402

REPO = M.REPO
roster = re.findall(r"\{ id: '([^']+)', name: '([^']+)'[^\n]*?base: '([^']*)'",
                    (REPO / "game/js/roster-full.js").read_text())
over = json.loads((REPO / "tools/moveset-merge/bases.json").read_text()).get("override", {})
print("# Moveset coverage per fighter (2026-10-23)\n")
print("Generated by `tools/moveset-merge/coverage_table.py` from the committed moveset files. "
      "T8 = wavu frame data (`docs/t7t8-reference/frame-data-t8-full`), T7 = t7chicken "
      "(`docs/t7t8-reference/frame-data-t7`). Covered = source records present in the fighter's file (by source id, or by the same canonical notation: T8 wins over T7 for one input). Records left over are rows `notation.canon()` cannot key (descriptions such as 'Face Up, Feet Towards+3'). "
      "CPU AI (`game/js/ai.js`) draws its attacks from every slotted input of the same file.\n")
print("| Fighter | Source character | T8 source | T8 covered | T7 source | T7 covered | Moves | Slotted inputs |")
print("|---|---|---|---|---|---|---|---|")
tot = [0, 0, 0, 0]
for fid, name, base in roster:
    p = REPO / f"game/assets/movesets/{fid}.json"
    if not p.exists():
        print(f"| {name} | {base} | - | - | - | - | **no file** | - |"); continue
    d = json.loads(p.read_text()); moves = d.get("moves") or {}
    B = M.bases_for(fid, d, over)
    have8, have7 = set(), set()
    for m in moves.values():
        if not isinstance(m, dict): continue
        if m.get("t8_id"): have8.add(m["t8_id"])
        ms = str(m.get("merge_source") or "")
        if ms.startswith("t8:"): have8.add(ms[3:])
        if ms.startswith("t7:"): have7.add(ms[3:])
        if isinstance(m.get("t7"), dict) and m["t7"].get("id"): have7.add(m["t7"]["id"])
    keys = set(moves) | set(d.get("slots") or {})
    keyed = lambda nota: bool(nota) and (nota in keys or any(k.split("~")[0] == nota for k in keys))
    s8 = set(); s7 = set()
    for n in B.get("t8", []):
        for r in M.t8_rows(n)[1]:
            s8.add(r["id"])
            if keyed(N.canon(r.get("input") or "")[0]): have8.add(r["id"])
    for n in B.get("t7", []):
        for r in M.t7_rows(n):
            if not r.get("id"): continue
            s7.add(r["id"])
            if keyed(N.canon(r.get("notation") or "")[0]): have7.add(r["id"])
    c8, c7 = len(s8 & have8), len(s7 & have7)
    tot[0] += c8; tot[1] += len(s8); tot[2] += c7; tot[3] += len(s7)
    f8 = ",".join(B.get("t8", [])) or "none (not in T8)"
    f7 = ",".join(B.get("t7", [])) or "none"
    pc = lambda a, b: f"{a}/{b} ({100*a//b}%)" if b else "-"
    slots = len(d.get("slots") or moves)
    print(f"| {name} | {base} | {f8} | {pc(c8, len(s8))} | {f7} | {pc(c7, len(s7))} | {len(moves)} | {slots} |")
print(f"\n**Total:** T8 {tot[0]}/{tot[1]} source records, T7 {tot[2]}/{tot[3]} source records carried.")
