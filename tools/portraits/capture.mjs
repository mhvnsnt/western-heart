// Regenerate select portraits from each fighter's attire-1 model in its own
// bank stance (game/portrait-capture.html). Serve the repo root on $WH_URL.
// Usage: node tools/portraits/capture.mjs [id,id,...]
import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = process.env.WH_URL || 'http://127.0.0.1:8822';
const OUT = 'game/assets/portraits';
const b = await chromium.launch({ channel: process.env.PW_CHANNEL || undefined, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
let p = await b.newPage({ viewport: { width: 320, height: 320 } });
p.on('console', m => { if (m.type() === 'warning' || m.type() === 'error') console.log('  [page]', m.text().slice(0, 200)); });
await p.goto(BASE + '/game/portrait-capture.html');
await p.waitForFunction(() => window.ready, null, { timeout: 60000 });
const only = process.argv[2] ? process.argv[2].split(',') : null;
const ids = only || await p.evaluate(() => window.rosterIds());
const manPath = `${OUT}/portraits-manifest.json`;
const man = fs.existsSync(manPath) ? JSON.parse(fs.readFileSync(manPath, 'utf8')) : { fighters: {} };
for (const id of ids) {
  if (ids.indexOf(id) > 0) { await p.close(); p = await b.newPage({ viewport: { width: 320, height: 320 } }); await p.goto(BASE + '/game/portrait-capture.html'); await p.waitForFunction(() => window.ready, null, { timeout: 60000 }); }
  let r;
  try { r = await p.evaluate((i) => window.capture(i), id); } catch (e) { r = { id, error: String(e.message || e).slice(0, 200) }; }
  if (r.png) { fs.writeFileSync(`${OUT}/${id}.png`, Buffer.from(r.png.split(',')[1], 'base64')); delete r.png; }
  man.fighters[id] = r;
  console.log(JSON.stringify(r));
}
man._doc = 'Generated by tools/portraits/capture.mjs (attire-1 model via attires.js, posed by its moveset bank stance through select-screen PreviewPane). Checked by test/portraits.test.mjs.';
fs.writeFileSync(manPath, JSON.stringify(man, null, 2) + '\n');  // 2-space: the committed format (a re-capture rewrites only its fighters' entries)
await b.close();
