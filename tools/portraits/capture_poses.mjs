// Owner t199u: every select card = the fighter's OWN attire-1 model in a
// UNIQUE idle from its own source Tekken bank, framed like Pantera's card
// (the quality bar). Buffalo Bill's pose is locked (second reference).
// For each visible fighter, candidate poses are tried in order (assigned
// clip, then the other clips of the same bank, then CMU windows) and the
// first render whose framing matches Pantera's (head/shoulder placement,
// coverage, centred, not a wide T-pose silhouette, not a blank texture)
// is kept. Writes game/assets/portraits/<id>.png, portraits-manifest.json
// and game/data/select-poses.json (the select screen + hero render read it).
// Usage: WH_URL=http://127.0.0.1:PORT node tools/portraits/capture_poses.mjs [id,...]
import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE = process.env.WH_URL || 'http://127.0.0.1:8822';
const OUT = 'game/assets/portraits', POSES = 'game/data/select-poses.json';
const CLIPS = [['stance', 't3_neutral.json'], ['intro', 't3_stance.json'], ['win_rp', 't3_win_rp.json'], ['win_lp', 't3_win_lp.json'],
  ['win_lk', 't3_win_lk.json'], ['win_rk', 't3_win_rk.json'], ['stance_b', 't3_stance_b.json'], ['stance_c', 't3_stance_c.json'], ['block', 't3_block.json']];
const LOCKED = { pantera: { bank: 'king', clip: 'stance', file: 't3_neutral.json' }, 'buffalo-bill': { bank: null, clip: 'cmu#0', cmu: { mirror: false, phase: 0 } } };
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
let p;
async function fresh(n = 0) { try { if (p) await p.close(); } catch {}
  try { p = await b.newPage({ viewport: { width: 320, height: 320 } }); await p.goto(BASE + '/game/portrait-capture.html'); await p.waitForFunction(() => window.ready, null, { timeout: 60000 }); }
  catch (e) { if (n >= 2) throw e; p = null; await fresh(n + 1); } }
await fresh();
const visible = await p.evaluate(() => window.visibleIds());
const assigned = await p.evaluate(() => window.assigned());
const only = process.argv[2] ? process.argv[2].split(',') : null;
const prev = fs.existsSync(POSES) ? JSON.parse(fs.readFileSync(POSES, 'utf8')) : { poses: {} };
const key = (q) => (q.bank ? `${q.bank}/${q.clip}` : q.clip);
const used = new Set();
for (const [id, q] of Object.entries(prev.poses)) if (only && !only.includes(id) && visible.includes(id)) used.add(key(q));
// reference
const ref = await p.evaluate(async () => { const r = await window.capture('pantera', {}); r.metrics = await window.score(r.png); return r; });
const R = ref.metrics;
console.log('pantera ref', JSON.stringify(R));
function ok(m) {
  const why = [];
  if (m.coverage < R.coverage * 0.45 || m.coverage > Math.min(0.92, R.coverage * 1.55)) why.push(`coverage ${m.coverage.toFixed(2)}`);
  if (Math.abs(m.top - R.top) > 0.16) why.push(`top ${m.top.toFixed(2)}`);
  if (Math.abs(m.cx - R.cx) > 0.17) why.push(`cx ${m.cx.toFixed(2)}`);
  if (m.left < 0.01 && m.right > 0.99 && m.upperRow > 0.97) why.push('wide silhouette (T-pose/clipped)');
  if (m.lumStd < 0.035) why.push('flat/blank texture');
  return why;
}
const man = fs.existsSync(`${OUT}/portraits-manifest.json`) ? JSON.parse(fs.readFileSync(`${OUT}/portraits-manifest.json`, 'utf8')) : { fighters: {} };
const poses = { ...prev.poses };
const order = ['buffalo-bill', 'pantera', ...visible.filter(i => i !== 'pantera' && i !== 'buffalo-bill')];
function save() {
for (const id of Object.keys(poses)) if (!visible.includes(id)) delete poses[id];
fs.writeFileSync(POSES, JSON.stringify({ _doc: 'Unique select pose per visible fighter (owner t199u). Written by tools/portraits/capture_poses.mjs; validated by test/select-poses.test.mjs. Keys: bank/clip from the fighter\'s own source T3 bank, or cmu#N windows where no source bank is decoded yet. pantera and buffalo-bill are owner-locked references.', reference: { pantera: R }, poses }, null, 1) + '\n');
man._doc = 'Generated by tools/portraits/capture_poses.mjs (attire-1 model, unique own-bank select pose, framed and checked against the Pantera card). Checked by test/portraits.test.mjs + test/select-poses.test.mjs.';
fs.writeFileSync(`${OUT}/portraits-manifest.json`, JSON.stringify(man, null, 1) + '\n');
}
let cmuN = 1;
for (const id of order) {
  if (only && !only.includes(id)) continue;
  const a = assigned[id] || {};
  let cands;
  if (LOCKED[id]) cands = [LOCKED[id]];
  else if (a.bank) cands = [a, ...CLIPS.filter(([c]) => c !== a.clip).map(([clip, file]) => ({ bank: a.bank, clip, file }))];
  else cands = [];
  for (let k = 0; k < 8; k++) { const n = cmuN + k; cands.push({ bank: null, clip: `cmu#${n}`, cmu: { mirror: n % 2 === 1, phase: (Math.floor(n / 2) * 0.37) % 2 } }); }
  let best = null, tries = [];
  for (const q of cands) {
    if (!LOCKED[id] && used.has(key(q))) continue;
    await fresh();
    let r;
    try { r = await p.evaluate(async ([i, q]) => { const r = await window.capture(i, { pose: q }); if (r.png) r.metrics = await window.score(r.png); return r; }, [id, q]); }
    catch (e) { r = { id, error: String(e.message || e).slice(0, 160) }; }
    if (r.error || !r.png) { tries.push(`${key(q)}: ${r.error || 'no png'}`); if (r.error === 'model failed to load') break; continue; }
    const why = LOCKED[id] ? [] : ok(r.metrics);
    if (!r.stance) why.push('no stance (bind pose)');
    tries.push(`${key(q)}: ${why.join(', ') || 'PASS'}`);
    if (!best || why.length < best.why.length) best = { q, r, why };
    if (!why.length) break;
  }
  if (!best) { man.fighters[id] = { id, error: tries.join(' | ') }; console.log(id, 'FAIL', tries.join(' | ')); continue; }
  const { q, r, why } = best;
  used.add(key(q)); if (!q.bank && q.clip !== 'cmu#0') cmuN = Math.max(cmuN, +q.clip.slice(4) + 1);
  poses[id] = q;
  fs.writeFileSync(`${OUT}/${id}.png`, Buffer.from(r.png.split(',')[1], 'base64'));
  delete r.png; r.poseKey = key(q); r.framingIssues = why; r.tries = tries;
  man.fighters[id] = r;
  save();
  console.log(id, key(q), why.length ? 'BEST-EFFORT ' + why.join(',') : 'PASS');
}
save();
await b.close();
